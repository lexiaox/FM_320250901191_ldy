import java.lang.reflect.Field;
import java.lang.reflect.Method;
import java.lang.reflect.Modifier;
import java.util.List;

/**
 * 业务规则自动自检程序（无交互，便于批改与复现）。
 *
 * <p>为什么单独写一个自检类，而不是只在主程序里手工点菜单？</p>
 * <ul>
 *   <li>业务规则分散在 {@link CosparId}、{@link Satellite}、{@link SatelliteManager}
 *       三处，逐条写断言可以证明每条规则都被真正执行；</li>
 *   <li>手工测试容易漏掉边界值（例如间距恰好 0.2、轨道恰好 1.2），
 *       自动测试可以精确定位；</li>
 *   <li>自检类不依赖界面，直接调用业务层，体现“界面与业务分离”的设计。</li>
 * </ul>
 *
 * <p>运行方式：{@code java -cp out Main check}。全部通过时最后输出“全部通过”。</p>
 *
 * <p>实现约束：按作业要求，本类不使用 static 方法，也不使用内部类或匿名类；
 * 需要“执行一段可能抛异常的代码”时，统一使用独立的 {@link TestAction} 实现类。</p>
 *
 * @author 乐豆芽
 * @version 1.0
 */
public class RuleChecker {

    /** 通过计数。 */
    private int passed;

    /** 失败计数。 */
    private int failed;

    /**
     * 构造自检程序。
     *
     * <p>本类没有 main 方法：除主类外不使用 static 方法，
     * 因此自检由 {@link Main} 以带参数 {@code check} 的方式启动。</p>
     */
    public RuleChecker() {
        // 无状态，直接使用
    }

    /**
     * 依次执行全部规则测试并输出汇总。
     */
    public void runAll() {
        System.out.println("================ 业务规则自动自检 ================");

        testR1OrbitFloor();
        testR2OrbitGap();
        testR3CosparFormat();
        testR4DuplicateId();
        testR5IdImmutable();
        testR6ArchivedIdCannotReuse();
        testR7LockedCannotModify();
        testR8ArchiveFreesOrbit();
        testR9TimeAutoGenerated();
        testR10PreloadAndCapacity();
        testR11SearchAndInput();

        System.out.println("--------------------------------------------------");
        System.out.printf("通过 %d 项，失败 %d 项%n", passed, failed);
        System.out.println(failed == 0 ? "全部通过" : "存在失败项，请检查");
        System.out.println("==================================================");
    }

    /**
     * 断言条件成立。
     *
     * @param condition 条件
     * @param message   说明
     */
    private void check(boolean condition, String message) {
        if (condition) {
            passed++;
            System.out.println("  [通过] " + message);
        } else {
            failed++;
            System.out.println("  [失败] " + message);
        }
    }

    /**
     * 断言某段代码抛出了指定类型的异常。
     *
     * @param message  说明
     * @param expected 期望的异常类型
     * @param action   待执行的动作
     */
    private void checkThrows(String message, Class<? extends Exception> expected, TestAction action) {
        try {
            action.run();
            failed++;
            System.out.println("  [失败] " + message + "（未抛出异常）");
        } catch (Exception e) {
            if (expected.isInstance(e)) {
                passed++;
                System.out.println("  [通过] " + message + " → " + e.getClass().getSimpleName()
                        + ": " + e.getMessage());
            } else {
                failed++;
                System.out.println("  [失败] " + message + "（抛出的是 " + e.getClass().getSimpleName()
                        + "，期望 " + expected.getSimpleName() + "）");
            }
        }
    }

    /** R1：最低轨道 1.2。 */
    private void testR1OrbitFloor() {
        System.out.println("R1 最低卫星轨道为 1.2");
        final SatelliteManager m = new SatelliteManager();
        checkThrows("轨道 1.19 应被拒绝", InvalidInputException.class, new TestAction() {
            @Override
            public void run() throws Exception {
                m.register("CN0101", "SUN_SYNC", "低轨测试", 1.19, "测试");
            }
        });
        try {
            // 预加载中 IN0006 恰好占用 1.20，这里单独校验“下限”本身，
            // 证明 1.2 不会因为浮点误差被误判为“小于 1.2”。
            m.checkOrbitFloor(1.2);
            check(true, "轨道恰好 1.2 通过下限校验（EPSILON 容差生效）");
            m.checkOrbitFloor(1.200000001);
            check(true, "轨道 1.200000001 通过下限校验");
        } catch (InvalidInputException e) {
            check(false, "轨道 1.2 被错误拒绝：" + e.getMessage());
        }
    }

    /** R2：轨道间距不小于 0.2。 */
    private void testR2OrbitGap() {
        System.out.println("R2 卫星轨道间距不得小于 0.2");
        final SatelliteManager m = new SatelliteManager();
        checkThrows("与 CN0001(3.60) 间距 0.19 应被拒绝", InvalidInputException.class, new TestAction() {
            @Override
            public void run() throws Exception {
                m.register("CN0201", "STABLE", "间距测试", 3.79, "测试");
            }
        });
        try {
            Satellite s = m.register("CN0202", "STABLE", "间距边界", 3.80, "间距恰好 0.2 应被接受");
            check(Math.abs(s.getOrbit() - 3.80) < 1e-9, "间距恰好 0.2 应被接受");
        } catch (InvalidInputException e) {
            check(false, "间距 0.2 被错误拒绝：" + e.getMessage());
        }
    }

    /** R3：COSPARID 格式。 */
    private void testR3CosparFormat() {
        System.out.println("R3 COSPARID 为 2 位国家编码 + 4 位数字");
        final String[] bad = {"CN001", "CN00A1", "ZZ0001"};
        final String[] reasons = {"长度 5 位", "含非数字字符", "未知国家编码"};
        for (int i = 0; i < bad.length; i++) {
            final String value = bad[i];
            checkThrows(reasons[i] + "应被拒绝", InvalidInputException.class, new TestAction() {
                @Override
                public void run() throws Exception {
                    new CosparId(value);
                }
            });
        }
        try {
            CosparId id = new CosparId("cn0101");
            check("CN0101".equals(id.getValue()) && "中国".equals(id.getCountryName()),
                    "小写输入应被规范化为大写 CN0101");
        } catch (InvalidInputException e) {
            check(false, "合法输入被拒绝：" + e.getMessage());
        }
    }

    /** R4：COSPARID 唯一。 */
    private void testR4DuplicateId() {
        System.out.println("R4 COSPARID 全局唯一");
        final SatelliteManager m = new SatelliteManager();
        checkThrows("重复的 CN0001 应被拒绝", InvalidInputException.class, new TestAction() {
            @Override
            public void run() throws Exception {
                m.register("CN0001", "STABLE", "重复", 6.50, "测试");
            }
        });
        check(!m.isCosparIdUsed("CN9999"), "未使用过的 CN9999 判定为未占用");
        check(m.isCosparIdUsed("cn0001"), "已使用的 CN0001 判定为已占用（大小写不敏感）");
    }

    /** R5：分配后不可修改。 */
    private void testR5IdImmutable() {
        System.out.println("R5 COSPARID 分配后不得修改");
        try {
            Field field = CosparId.class.getDeclaredField("value");
            check(Modifier.isFinal(field.getModifiers()), "CosparId.value 字段为 final");
        } catch (NoSuchFieldException e) {
            check(false, "找不到 CosparId.value 字段");
        }
        boolean hasSetter = false;
        Method[] methods = CosparId.class.getDeclaredMethods();
        for (int i = 0; i < methods.length; i++) {
            if (methods[i].getName().startsWith("set")) {
                hasSetter = true;
            }
        }
        check(!hasSetter, "CosparId 不提供任何 setter 方法");
        try {
            SatelliteManager m = new SatelliteManager();
            Satellite s = m.findByCosparId("CN0001");
            s.rename("天眼一号（改名不改变 ID）");
            check("CN0001".equals(s.getCosparId().getValue()), "改名后 COSPARID 保持不变");
        } catch (Exception e) {
            check(false, "改名测试异常：" + e.getMessage());
        }
    }

    /** R6：归档后 ID 不可复用。 */
    private void testR6ArchivedIdCannotReuse() {
        System.out.println("R6 报废归档的 COSPARID 不能再次使用");
        final SatelliteManager m = new SatelliteManager();
        try {
            m.deleteAndArchive("JP0004");
            check(m.getArchivedCount() == 1, "JP0004 已移入归档集合");
            check(m.findByCosparId("JP0004") == null, "JP0004 已从在用列表移除");
            checkThrows("用归档过的 JP0004 重新注册应被拒绝", InvalidInputException.class,
                    new TestAction() {
                        @Override
                        public void run() throws Exception {
                            m.register("JP0004", "SUN_SYNC", "复用测试", 1.90, "测试");
                        }
                    });
        } catch (Exception e) {
            check(false, "归档测试异常：" + e.getMessage());
        }
    }

    /** R7：封锁状态不可修改。 */
    private void testR7LockedCannotModify() {
        System.out.println("R7 封锁后不得修改信息和删除（须先激活）");
        final SatelliteManager m = new SatelliteManager();
        checkThrows("封锁的 JP0004 改名应被拒绝", IllegalStateException.class, new TestAction() {
            @Override
            public void run() throws Exception {
                m.rename("JP0004", "改名测试");
            }
        });
        checkThrows("激活状态的 CN0001 不能被直接删除", IllegalStateException.class, new TestAction() {
            @Override
            public void run() throws Exception {
                m.deleteAndArchive("CN0001");
            }
        });
        checkThrows("封锁的 JP0004 不能再次封锁", IllegalStateException.class, new TestAction() {
            @Override
            public void run() throws Exception {
                m.deactivate("JP0004");
            }
        });
    }

    /** R8：归档腾出轨道空间。 */
    private void testR8ArchiveFreesOrbit() {
        System.out.println("R8 报废删除后应腾出轨道空间");
        SatelliteManager m = new SatelliteManager();
        try {
            m.deleteAndArchive("JP0004");
            Satellite s = m.register("CN0801", "SUN_SYNC", "接替卫星", 1.50, "使用 1.50 轨道接替辉夜二号");
            check(s != null && m.getActiveCount() == 6, "JP0004 腾出的 1.50 轨道可被新卫星使用");
        } catch (Exception e) {
            check(false, "轨道复用失败：" + e.getMessage());
        }
    }

    /** R9：时间由系统产生。 */
    private void testR9TimeAutoGenerated() {
        System.out.println("R9 注册时间与修改时间由系统自动产生");
        SatelliteManager m = new SatelliteManager();
        try {
            Satellite s = m.findByCosparId("CN0001");
            int before = s.getHistory().size();
            s.rename("天眼一号-新");
            s.deactivate();
            s.activate();
            List<ModifyRecord> history = s.getHistory();
            check(history.size() == before + 3, "改名、封锁、激活各追加一条记录");
            check(history.get(history.size() - 1).getTime() != null, "记录时间由系统产生且非空");
            boolean modifiable;
            try {
                history.add(new ModifyRecord(null, "伪造", "外部伪造记录"));
                modifiable = true;
            } catch (UnsupportedOperationException e) {
                modifiable = false;
            }
            check(!modifiable, "getHistory() 返回只读视图，外部无法追加记录");
        } catch (Exception e) {
            check(false, "时间测试异常：" + e.getMessage());
        }
    }

    /** R10：预加载与初始容量。 */
    private void testR10PreloadAndCapacity() {
        System.out.println("R10 预加载不少于 5 颗，ArrayList 初始容量为 10");
        SatelliteManager m = new SatelliteManager();
        check(m.getActiveCount() >= 5, "启动时预加载 " + m.getActiveCount() + " 颗（≥5）");
        check(SatelliteManager.INITIAL_CAPACITY == 10, "INITIAL_CAPACITY = 10");
    }

    /** R11：查找与非法输入。 */
    private void testR11SearchAndInput() {
        System.out.println("R11 模糊查找与非法输入拦截");
        final SatelliteManager m = new SatelliteManager();
        try {
            check(m.search("天眼").size() == 1, "关键字“天眼”命中 1 条");
            check(m.search("cn").size() >= 1, "关键字“cn”（小写）能命中中国卫星");
            check(m.search("不存在的卫星").isEmpty(), "无匹配时返回空列表");
            checkThrows("空关键字应被拒绝", InvalidInputException.class, new TestAction() {
                @Override
                public void run() throws Exception {
                    m.search("   ");
                }
            });
            checkThrows("空名称应被拒绝", InvalidInputException.class, new TestAction() {
                @Override
                public void run() throws Exception {
                    m.register("CN1101", "STABLE", "  ", 6.00, "测试");
                }
            });
            checkThrows("不存在的 ID 应抛出找不到异常", SatelliteNotFoundException.class, new TestAction() {
                @Override
                public void run() throws Exception {
                    m.activate("ZZ9999");
                }
            });
        } catch (Exception e) {
            check(false, "查找测试异常：" + e.getMessage());
        }
    }
}
